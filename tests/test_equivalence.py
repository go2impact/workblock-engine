# ── Workblock-level equivalence ─────────────────────────────────────


class TestWorkblockEquivalence:

    def test_same_users(self, we_result, golden):
        we_users = sorted(
            we_result.workblocks["user_id"].unique().to_list()
            if not we_result.workblocks.is_empty() else []
        )
        assert we_users == sorted(golden.keys())

    def test_no_skipped_users(self, we_result):
        assert we_result.skipped_users == []

    def test_workblock_count_per_user(self, we_result, golden):
        we_wbs = _wb_by_user(we_result)
        for uid in golden:
            expected = len(golden[uid]["workblocks"])
            actual = len(we_wbs.get(uid, []))
            assert expected == actual, f"{uid}: {expected} vs {actual} workblocks"

    def test_workblock_ids_match(self, we_result, golden):
        we_wbs = _wb_by_user(we_result)
        for uid in golden:
            expected = [wb["workblock_id"] for wb in golden[uid]["workblocks"]]
            actual = [wb["workblock_id"] for wb in we_wbs.get(uid, [])]
            assert expected == actual, f"{uid}: workblock ID mismatch"

    def test_workblock_boundaries(self, we_result, golden):
        we_wbs = _wb_by_user(we_result)
        for uid in golden:
            for i, (exp, act) in enumerate(
                zip(golden[uid]["workblocks"], we_wbs.get(uid, []), strict=True)
            ):
                assert exp["start_time"] == _normalize_ts(act["start_time"]), (
                    f"{uid} wb[{i}] start: {exp['start_time']} vs {act['start_time']}"
                )
                assert exp["end_time"] == _normalize_ts(act["end_time"]), (
                    f"{uid} wb[{i}] end: {exp['end_time']} vs {act['end_time']}"
                )

    def test_workblock_durations(self, we_result, golden):
        we_wbs = _wb_by_user(we_result)
        for uid in golden:
            for i, (exp, act) in enumerate(
                zip(golden[uid]["workblocks"], we_wbs.get(uid, []), strict=True)
            ):
                assert _approx(exp["duration_minutes"], act["duration_minutes"]), (
                    f"{uid} wb[{i}]: {exp['duration_minutes']} vs {act['duration_minutes']}"
                )
                assert _approx(exp["active_duration_minutes"], act["active_duration_minutes"]), (
                    f"{uid} wb[{i}]: {exp['active_duration_minutes']} vs {act['active_duration_minutes']}"
                )

    def test_workblock_activity_counts(self, we_result, golden):
        we_wbs = _wb_by_user(we_result)
        for uid in golden:
            for i, (exp, act) in enumerate(
                zip(golden[uid]["workblocks"], we_wbs.get(uid, []), strict=True)
            ):
                assert exp["total_activities"] == act["total_activities"], (
                    f"{uid} wb[{i}]: {exp['total_activities']} vs {act['total_activities']}"
                )


